// Package model holds the public content model of sitemaker: pages,
// taxonomy terms and the site graph. It is shared by the build pipeline,
// the theme templates and third-party plugins, so it intentionally has no
// dependency on any internal package.
package model

import (
	"html/template"
	"sort"
	"time"
)

// Kind classifies a rendered page; themes use it to pick a layout.
type Kind string

const (
	KindHome     Kind = "home"
	KindPost     Kind = "post"
	KindPage     Kind = "page"
	KindList     Kind = "list"     // the paginated article index
	KindTerms    Kind = "terms"    // /tags/, /categories/
	KindTerm     Kind = "term"     // /tags/<slug>/
	KindArchive  Kind = "archive"  // /archives/
	KindSearch   Kind = "search"   // /search/
	KindNotFound Kind = "404"
	KindCustom   Kind = "custom" // generated by plugins
)

// Page is one Markdown document (a post or a standalone page) after it
// has been parsed and rendered.
type Page struct {
	Kind       Kind
	SourcePath string // relative to the site root, e.g. content/posts/foo.md
	Section    string // first directory under content/, e.g. "posts"

	Slug      string
	URL       string // site-relative, always starts with "/"
	Permalink string // absolute, empty when site.url is unset

	Title       string
	Description string
	Author      string
	Location    string
	Avatar      string
	Cover       string
	Category    string
	Tags        []string
	Lang        string
	Layout      string
	Draft       bool
	TOC         bool
	Weight      int

	Date    time.Time
	Updated time.Time

	// Params carries every front matter key, including unknown ones, so
	// themes and plugins can read custom fields: {{.Page.Params.mood}}.
	Params map[string]any

	Body           string        // Markdown source after the front matter
	Content        template.HTML // rendered HTML
	Excerpt        string        // plain-text summary
	PlainText      string        // full plain text, used for search/word count
	WordCount      int
	ReadingMinutes int

	// Filled by the site graph after every page is loaded.
	CategoryTerm *Term
	TagTerms     []*Term
	Prev, Next   *Page // chronological neighbours (posts only)
	Related      []*Page
}

// DateString returns the publish date as YYYY-MM-DD, or "" when unset.
func (p *Page) DateString() string { return formatDate(p.Date) }

// UpdatedString returns the update date as YYYY-MM-DD, or "" when unset.
func (p *Page) UpdatedString() string { return formatDate(p.Updated) }

// LastMod is the most recent of Date and Updated.
func (p *Page) LastMod() time.Time {
	if p.Updated.After(p.Date) {
		return p.Updated
	}
	return p.Date
}

// Param returns a front matter value or nil.
func (p *Page) Param(key string) any {
	if p.Params == nil {
		return nil
	}
	return p.Params[key]
}

func formatDate(t time.Time) string {
	if t.IsZero() {
		return ""
	}
	return t.Format("2006-01-02")
}

// Term is one value of a taxonomy (a tag or a category) with its pages.
type Term struct {
	Taxonomy    string // "tags" or "categories"
	Name        string
	Slug        string
	URL         string
	Description string
	Pages       []*Page // newest first
}

// Count is the number of pages filed under the term.
func (t *Term) Count() int { return len(t.Pages) }

// Taxonomy is an ordered set of terms.
type Taxonomy struct {
	Name  string // "tags" | "categories"
	Title string // "Tags" | "Categories"
	URL   string
	Terms []*Term
	index map[string]*Term
}

// NewTaxonomy creates an empty taxonomy.
func NewTaxonomy(name, title, url string) *Taxonomy {
	return &Taxonomy{Name: name, Title: title, URL: url, index: map[string]*Term{}}
}

// Get returns the term with the given slug, or nil.
func (t *Taxonomy) Get(slug string) *Term {
	if t == nil {
		return nil
	}
	return t.index[slug]
}

// Ensure returns the term for slug, creating it when missing.
func (t *Taxonomy) Ensure(name, slug string) *Term {
	if term, ok := t.index[slug]; ok {
		return term
	}
	term := &Term{Taxonomy: t.Name, Name: name, Slug: slug, URL: t.URL + slug + "/"}
	t.index[slug] = term
	t.Terms = append(t.Terms, term)
	return term
}

// ByCount returns the terms ordered by page count (desc), then name.
func (t *Taxonomy) ByCount() []*Term {
	out := append([]*Term(nil), t.Terms...)
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].Count() != out[j].Count() {
			return out[i].Count() > out[j].Count()
		}
		return out[i].Name < out[j].Name
	})
	return out
}

// Site is the whole content graph handed to templates and plugins.
type Site struct {
	Title       string
	URL         string // without trailing slash
	Description string
	Language    string
	Author      string

	Posts      []*Page // published posts, newest first
	Pages      []*Page // standalone pages
	Tags       *Taxonomy
	Categories *Taxonomy

	// Params mirrors the free-form `params:` block of _config.yaml.
	Params map[string]any
	// Data holds values plugins want to expose to every template.
	Data map[string]any

	BuildTime time.Time
	Drafts    bool // true when drafts are being rendered (serve --drafts)
}

// AllPages returns posts followed by standalone pages.
func (s *Site) AllPages() []*Page {
	out := make([]*Page, 0, len(s.Posts)+len(s.Pages))
	out = append(out, s.Posts...)
	return append(out, s.Pages...)
}

// PageByURL finds a post or page by its site-relative URL.
func (s *Site) PageByURL(url string) *Page {
	for _, p := range s.AllPages() {
		if p.URL == url {
			return p
		}
	}
	return nil
}

// Abs turns a site-relative path into an absolute URL when site.url is set.
func (s *Site) Abs(path string) string {
	if s.URL == "" {
		return path
	}
	if path == "" || path[0] != '/' {
		path = "/" + path
	}
	return s.URL + path
}

// VirtualPage is a page produced by a plugin generator and rendered
// through the theme like any other page.
type VirtualPage struct {
	URL     string // site-relative output URL, e.g. /now/ or /stats.html
	Layout  string // theme layout name without extension, e.g. "page"
	Title   string
	Content template.HTML
	NoIndex bool
	Data    map[string]any // exposed to the template as .Data
}

// OutputFile is a raw file written verbatim to the output directory.
type OutputFile struct {
	Path    string // relative to the output root, e.g. "manifest.json"
	Content []byte
}
